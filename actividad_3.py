import ipywidgets as widgets
from IPython.display import display, HTML
import statistics
from ipywidgets import ButtonStyle

class GradeCalculatorWidget:
    def __init__(self):
        # Input widgets
        self.grade_inputs = []
        for i in range(5):
            self.grade_inputs.append(widgets.FloatText(
                description=f'Nota {i+1}:',
                min=0.0,
                max=100.0,
                value=0.0,
                step=0.1,
                continuous_update=False
            ))

        # Output widgets
        self.output_avg = widgets.HTML(value="<p><b>Promedio:</b></p>")
        self.output_std_dev = widgets.HTML(value="<p><b>Desviación Estándar:</b></p>")
        self.output_max = widgets.HTML(value="<p><b>Mayor Nota:</b></p>")
        self.output_min = widgets.HTML(value="<p><b>Menor Nota:</b></p>")
        self.output_error = widgets.HTML(value="<p style='color:red;'></p>")

        # Define custom button style
        custom_button_style = ButtonStyle(button_color='#BC89CC')

        self.calculate_button = widgets.Button(
            description="Calcular",
            button_style='',
            style=custom_button_style # Apply the custom style here
        )
        self.calculate_button.on_click(self._calculate_grades)

        # Arrange widgets in containers
        self.grade_input_box = widgets.VBox(self.grade_inputs)
        self.result_output_box = widgets.VBox([
            self.output_avg,
            self.output_std_dev,
            self.output_max,
            self.output_min,
            self.output_error
        ])

        # Create the main display box
        self.main_box = widgets.VBox([
            self.grade_input_box,
            self.calculate_button,
            self.result_output_box
        ])

    def _calculate_grades(self, b):

        grades = []
        self.output_error.value = ""
        for i, input_widget in enumerate(self.grade_inputs):
            try:
                grade = input_widget.value
                if not (0 <= grade <= 100):
                    self.output_error.value = f"<p style='color:red;'>La Nota {i+1} debe estar entre 0 y 100.</p>"
                    return
                grades.append(grade)
            except ValueError:
                self.output_error.value = f"<p style='color:red;'>Por favor, ingrese un número válido para la Nota {i+1}.</p>"
                return

        if len(grades) == 5:
            # Calculate statistics
            average = sum(grades) / len(grades)
            std_dev = statistics.stdev(grades) if len(grades) > 1 else 0.0
            highest = max(grades)
            lowest = min(grades)

            # Update output widgets
            self.output_avg.value = f"<p><b>Promedio:</b> {average:.2f}</p>"
            self.output_std_dev.value = f"<p><b>Desviación Estándar:</b> {std_dev:.2f}</p>"
            self.output_max.value = f"<p><b>Mayor Nota:</b> {highest:.2f}</p>"
            self.output_min.value = f"<p><b>Menor Nota:</b> {lowest:.2f}</p>"
        else:
            self.output_error.value = "<p style='color:red;'>Por favor, ingrese las cinco notas.</p>"

    def display_widget(self):
        """Method to display the organized widget."""
        display(self.main_box)

