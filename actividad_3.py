# ================= CILINDRO =================

class Cilindro(FiguraGeometrica):

    def __init__(self, radio, altura):
        if radio <= 0 or altura <= 0:
            raise ValueError("El radio y la altura deben ser positivos.")
        self.radio = radio
        self.altura = altura

    def calcular_volumen(self):
        return math.pi * self.radio**2 * self.altura

    def calcular_area(self):
        return 2 * math.pi * self.radio * (self.radio + self.altura)


# ================= ESFERA =================

class Esfera(FiguraGeometrica):

    def __init__(self, radio):
        if radio <= 0:
            raise ValueError("El radio debe ser positivo.")
        self.radio = radio

    def calcular_volumen(self):
        return (4/3) * math.pi * self.radio**3

    def calcular_area(self):
        return 4 * math.pi * self.radio**2


# ================= PIRÁMIDE =================

class Piramide(FiguraGeometrica):

    def __init__(self, base, altura, apotema):
        if base <= 0 or altura <= 0 or apotema <= 0:
            raise ValueError("La base, altura y apotema deben ser positivos.")
        self.base = base
        self.altura = altura
        self.apotema = apotema

    def calcular_volumen(self):
        # Assuming a square base pyramid
        return (self.base**2 * self.altura) / 3

    def calcular_area(self):
        area_base = self.base**2
        # Lateral area of a square base pyramid with apotema
        area_lateral = 2 * self.base * self.apotema
        return area_base + area_lateral


# ================= INTERFAZ GRÁFICA con ipywidgets =================

class GeometricFigureCalculatorWidget:

    def __init__(self):
        # Dropdown for figure selection
        self.figure_selector = widgets.Dropdown(
            options=['Cilindro', 'Esfera', 'Pirámide'],
            value='Cilindro',
            description='Seleccione una figura:',
            disabled=False,
        )
        self.figure_selector.observe(self._update_inputs, names='value')

        self.radio_input = widgets.FloatText(description='Radio (cm):', min=0.0, value=1.0)
        self.altura_input = widgets.FloatText(description='Altura (cm):', min=0.0, value=1.0)
        self.base_input = widgets.FloatText(description='Base (cm):', min=0.0, value=1.0)
        self.apotema_input = widgets.FloatText(description='Apotema (cm):', min=0.0, value=1.0)

        self.inputs_output = widgets.VBox([])

        custom_button_style = ButtonStyle(button_color='#BC89CC')

        # Calculate button
        self.calculate_button = widgets.Button(
            description='Calcular',
            button_style='',
            style=custom_button_style,
            tooltip='Calcular volumen y área',
        )
        self.calculate_button.on_click(self._calculate)

        # Result display
        self.result_output = widgets.HTML(value="<p><b>Volumen:</b></p><p><b>Área Superficial:</b></p>")
        self.error_output = widgets.HTML(value="", layout=widgets.Layout(width='auto'))

        # Main layout
        self.main_box = widgets.VBox([
            self.figure_selector,
            self.inputs_output,
            self.calculate_button,
            self.result_output,
            self.error_output
        ])

        # Initial update of inputs
        self._update_inputs(None)

    def _update_inputs(self, change):
        selected_figure = self.figure_selector.value
        current_inputs = []

        if selected_figure == 'Cilindro':
            current_inputs = [self.radio_input, self.altura_input]
        elif selected_figure == 'Esfera':
            current_inputs = [self.radio_input]
        elif selected_figure == 'Pirámide':
            current_inputs = [self.base_input, self.altura_input, self.apotema_input]

        self.inputs_output.children = current_inputs
        self.error_output.value = ""
        self.result_output.value = "<p><b>Volumen:</b></p><p><b>Área Superficial:</b></p>"


    def _calculate(self, b):
        selected_figure = self.figure_selector.value
        figure_object = None
        self.error_output.value = ""
        self.result_output.value = "<p><b>Volumen:</b></p><p><b>Área Superficial:</b></p>"

        try:
            if selected_figure == 'Cilindro':
                radio = self.radio_input.value
                altura = self.altura_input.value
                figure_object = Cilindro(radio, altura)
            elif selected_figure == 'Esfera':
                radio = self.radio_input.value
                figure_object = Esfera(radio)
            elif selected_figure == 'Pirámide':
                base = self.base_input.value
                altura = self.altura_input.value
                apotema = self.apotema_input.value
                figure_object = Piramide(base, altura, apotema)

            if figure_object:
                volumen = figure_object.calcular_volumen()
                area = figure_object.calcular_area()
                self.result_output.value = (
                    f"<p><b>Volumen:</b> {volumen:.2f} cm³</p>"
                    f"<p><b>Área Superficial:</b> {area:.2f} cm²</p>"
                )
        except ValueError as e:
            self.error_output.value = f"<p style='color:red;'>Error: {e}</p>"
        except Exception as e:
            self.error_output.value = f"<p style='color:red;'>Error inesperado: {e}</p>"

    def display_widget(self):
        display(self.main_box)

